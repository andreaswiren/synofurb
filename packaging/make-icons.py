#!/usr/bin/env python3
"""Regenerates the PLACEHOLDER application icons in packaging/icons/ (needs Pillow: pip install pillow).

The committed icons are generated by this script so they are reproducible; replace them (and keep the file names)
once the design team has final artwork. All formats cargo-packager needs are produced:
32x32.png, 128x128.png, 128x128@2x.png (256 px), 512x512.png, icon.png (= 512), icon.ico, icon.icns.
"""
from pathlib import Path

from PIL import Image, ImageDraw

OUT = Path(__file__).resolve().parent / "icons"
BG, BAY, LED = (26, 43, 72, 255), (214, 224, 240, 255), (86, 214, 138, 255)


def render(size: int) -> Image.Image:
    s = 8  # supersampling for clean edges
    big = size * s
    img = Image.new("RGBA", (big, big), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    r = int(big * 0.2)
    d.rounded_rectangle((0, 0, big - 1, big - 1), r, fill=BG)
    # four drive bays (a NAS front) with an activity LED each
    pad, gap = int(big * 0.17), int(big * 0.045)
    bay_h = (big - 2 * pad - 3 * gap) // 4
    for i in range(4):
        y = pad + i * (bay_h + gap)
        d.rounded_rectangle((pad, y, big - pad, y + bay_h), int(bay_h * 0.28), fill=BAY)
        cx, cy, rr = big - pad - int(bay_h * 0.62), y + bay_h // 2, int(bay_h * 0.17)
        d.ellipse((cx - rr, cy - rr, cx + rr, cy + rr), fill=LED if i == 0 else (150, 164, 188, 255))
    return img.resize((size, size), Image.LANCZOS)


def main() -> None:
    OUT.mkdir(exist_ok=True)
    sizes = {"32x32.png": 32, "128x128.png": 128, "128x128@2x.png": 256, "512x512.png": 512, "icon.png": 512}
    for name, px in sizes.items():
        render(px).save(OUT / name, optimize=True)
    big = render(1024)
    big.save(OUT / "icon.ico", sizes=[(16, 16), (24, 24), (32, 32), (48, 48), (64, 64), (128, 128), (256, 256)])
    big.save(OUT / "icon.icns")
    print("wrote", ", ".join(sorted(p.name for p in OUT.iterdir())))


if __name__ == "__main__":
    main()
