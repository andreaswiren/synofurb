class Workspace(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.mkdtemp(prefix="sbomtest-")
        self.addCleanup(shutil.rmtree, self.tmp, True)
        self.repo = os.path.join(self.tmp, "repo")
        os.makedirs(os.path.join(self.repo, "apps/mgmt-plane"))
        with open(os.path.join(self.repo, "apps/mgmt-plane/VERSION"), "w") as f:
            f.write("0.5.0\n")
        with open(os.path.join(self.repo, "apps/mgmt-plane/synofurb_mgmt.py"), "w") as f:
            f.write("import os\nimport json\nfrom http.server import BaseHTTPRequestHandler\n")
        with open(os.path.join(self.repo, "LICENSE"), "w") as f:
            f.write("MIT License\n\nCopyright (c) test\n")
        os.makedirs(os.path.join(self.repo, "scripts"))
        with open(os.path.join(self.repo, "scripts/build-kexec.sh"), "w") as f:
            f.write("VERSION=2.0.32\nSHA256=%s\n" % ("c" * 64))
        self.meta = make_meta(self.tmp)
        self.meta_path = os.path.join(self.tmp, "meta.json")
        with open(self.meta_path, "w") as f:
            json.dump(self.meta, f)
        self.lock_path = os.path.join(self.tmp, "Cargo.lock")
        with open(self.lock_path, "w") as f:
            f.write(LOCK)
        self.out = os.path.join(self.tmp, "out")

    def run_main(self, *extra):
        buf, err = io.StringIO(), io.StringIO()
        with redirect_stdout(buf), redirect_stderr(err):
            rc = sb.main(["--repo", self.repo, "--metadata", self.meta_path, "--cargo-lock", self.lock_path, "--out", self.out,
                          "--timestamp", "2026-11-02T00:00:00Z", *extra])
        return rc, buf.getvalue(), err.getvalue()

    def cdx(self):
        with open(os.path.join(self.out, "synofurb-1.2.3-sbom.cdx.json")) as f:
            return json.load(f)


class TestSpdxExpressions(unittest.TestCase):
    def test_normalise_and_render(self):
        self.assertEqual(sb.render_expression(sb.parse_expression("MIT/Apache-2.0")), "MIT OR Apache-2.0")
        self.assertEqual(sb.render_expression(sb.parse_expression("(MIT OR Apache-2.0) AND BSD-3-Clause")), "(MIT OR Apache-2.0) AND BSD-3-Clause")
        self.assertEqual(sb.render_expression(sb.parse_expression("Apache-2.0 WITH LLVM-exception OR MIT")), "Apache-2.0 WITH LLVM-exception OR MIT")
        self.assertEqual(sb.render_expression(sb.parse_expression("MIT / Apache-2.0")), "MIT OR Apache-2.0")

    def test_invalid(self):
        for bad in ("", "MIT OR", "(MIT", "MIT AND AND Zlib", "MIT WITH"):
            with self.assertRaises(sb.SpdxError, msg=bad):
                sb.parse_expression(bad)

    def test_copyleft_logic(self):
        f = lambda e: sb.copyleft_applies(sb.parse_expression(e))
        self.assertTrue(f("GPL-3.0-only"))
        self.assertTrue(f("MPL-2.0"))
        self.assertFalse(f("MIT OR GPL-2.0-only"))          # the licensee can choose MIT
        self.assertTrue(f("MIT AND LGPL-2.1-or-later"))      # both apply
        self.assertTrue(f("GPL-2.0-only OR LGPL-2.1-only"))  # every branch is copyleft
        self.assertFalse(f("MIT OR Apache-2.0"))
        self.assertEqual(sb.copyleft_family("AGPL-3.0-only")[0], "AGPL")
        self.assertEqual(sb.copyleft_family("LGPL-2.1-or-later")[0], "LGPL")
        self.assertEqual(sb.copyleft_family("GPL-2.0-only")[0], "GPL")
        self.assertIsNone(sb.copyleft_family("Apache-2.0"))


class TestCargoParts(unittest.TestCase):
    def test_lock_parsers_agree(self):
        a = sb.parse_cargo_lock(LOCK)
        saved = sb.tomllib
        try:
            sb.tomllib = None
            b = sb.parse_cargo_lock(LOCK)
        finally:
            sb.tomllib = saved
        self.assertEqual(a, b)
        self.assertEqual(len(a), 2)
        self.assertEqual(a[("libmit", "0.1.0", REG)], "a" * 64)

    def test_classification(self):
        with tempfile.TemporaryDirectory() as t:
            meta = make_meta(t)
        cls = sb.classify_dependencies(meta)
        kind = lambda n, v, ws=False: cls[pid(n, v, ws)]["kind"]
        self.assertEqual(kind("libmit", "0.1.0"), "normal")
        self.assertEqual(kind("buildtool", "3.0.0"), "build")
        self.assertEqual(kind("devtool", "4.0.0"), "dev")
        self.assertTrue(cls[pid("winonly", "0.9.0")]["conditional"])
        self.assertFalse(cls[pid("libmit", "0.1.0")]["conditional"])


