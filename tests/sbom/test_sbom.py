class TestValidator(Workspace):
    def good(self):
        self.run_main()
        return self.cdx()

    def errors(self, doc):
        return sb.check_cyclonedx(doc)[0]

    def test_duplicate_bom_ref(self):
        d = self.good()
        d["components"].append(copy.deepcopy(d["components"][0]))
        self.assertTrue(any("duplicate bom-ref" in e for e in self.errors(d)))

    def test_dangling_dependency(self):
        d = self.good()
        d["dependencies"][0]["dependsOn"].append("pkg:cargo/nothere@1.0.0")
        self.assertTrue(any("unknown ref" in e for e in self.errors(d)))
        d = self.good()
        d["dependencies"].append({"ref": "pkg:cargo/ghost@1.0.0", "dependsOn": []})
        self.assertTrue(any("is not a component" in e for e in self.errors(d)))

    def test_missing_version_and_licence(self):
        d = self.good()
        c = next(c for c in d["components"] if c["name"] == "libmit")
        del c["version"]
        self.assertTrue(any("without version" in e for e in self.errors(d)))
        d = self.good()
        c = next(c for c in d["components"] if c["name"] == "libmit")
        del c["licenses"]
        self.assertTrue(any("no licence and not listed" in e for e in self.errors(d)))

    def test_bad_hash_type_expression_header(self):
        d = self.good()
        next(c for c in d["components"] if c["name"] == "libmit")["hashes"][0]["content"] = "xyz"
        self.assertTrue(any("bad hash" in e for e in self.errors(d)))
        d = self.good()
        next(c for c in d["components"] if c["name"] == "libmit")["licenses"] = [{"expression": "MIT OR"}]
        self.assertTrue(any("not valid SPDX syntax" in e for e in self.errors(d)))
        d = self.good()
        d["specVersion"] = "1.4"
        d["serialNumber"] = "nope"
        e = self.errors(d)
        self.assertTrue(any("specVersion" in x for x in e) and any("serialNumber" in x for x in e))

    def test_check_cli_exit_codes(self):
        self.run_main()
        good = os.path.join(self.out, "synofurb-1.2.3-sbom.cdx.json")
        with redirect_stdout(io.StringIO()), redirect_stderr(io.StringIO()):
            self.assertEqual(sb.main(["--check", good, os.path.join(self.out, "synofurb-1.2.3-sbom.spdx.json")]), 0)
        d = self.cdx()
        d["components"][0]["bom-ref"] = d["components"][1]["bom-ref"]
        bad = os.path.join(self.tmp, "bad.json")
        with open(bad, "w") as f:
            json.dump(d, f)
        with redirect_stdout(io.StringIO()), redirect_stderr(io.StringIO()):
            self.assertEqual(sb.main(["--check", bad]), 1)
            self.assertEqual(sb.main(["--check", os.path.join(self.tmp, "missing.json")]), 1)

    def test_spdx_validator(self):
        self.run_main()
        with open(os.path.join(self.out, "synofurb-1.2.3-sbom.spdx.json")) as f:
            d = json.load(f)
        d["relationships"].append({"spdxElementId": "SPDXRef-nope", "relationshipType": "DEPENDS_ON", "relatedSpdxElement": "SPDXRef-DOCUMENT"})
        d["packages"].append(copy.deepcopy(d["packages"][0]))
        e = sb.check_spdx(d)[0]
        self.assertTrue(any("unknown SPDXRef-nope" in x for x in e) and any("duplicate SPDXID" in x for x in e))


class TestLicenceCollector(Workspace):
    def test_collects_dedups_and_reports_missing(self):
        for name, files in (("libmit", {"LICENSE-MIT": "MIT text\n", "LICENSE-APACHE": "Apache text\n"}),
                            ("copyleft-dep", {"LICENSE": "MPL text\n"}), ("weird", {"COPYING": "MIT text\r\n"})):
            d = os.path.join(self.tmp, "crates", name)
            os.makedirs(d, exist_ok=True)
            for fn, txt in files.items():
                with open(os.path.join(d, fn), "w", newline="") as f:
                    f.write(txt)
        pkgs, groups, missing, from_archive = lic.collect(sb, self.meta)
        names = {p["name"] for p in pkgs}
        self.assertEqual(names, {"libmit", "copyleft-dep", "winonly", "nolicense", "weird"})  # normal kind, no workspace, no build/dev
        self.assertEqual(len(groups), 3)  # "MIT text" is shared by libmit and weird (CRLF normalised)
        shared = next(g for g in groups.values() if g["text"] == "MIT text\n")
        self.assertEqual({w[0] for w in shared["who"]}, {"libmit", "weird"})
        self.assertEqual({m[0] for m in missing}, {"winonly", "nolicense"})
        text = lic.render(sb, self.repo, "1.2.3", pkgs, groups, missing)
        self.assertIn("PART 4 - crates with NO licence file in their source (2)", text)
        self.assertIn("MPL-2.0 crates", text)
        self.assertIn("copyleft-dep 2.0.0", text)
        self.assertEqual(text, lic.render(sb, self.repo, "1.2.3", pkgs, groups, missing))


