def slurp_dir(d):
    out = {}
    for f in os.listdir(d):
        with open(os.path.join(d, f), "rb") as fh:
            out[f] = fh.read()
    return out


REG = "registry+https://github.com/rust-lang/crates.io-index"


def pid(name, ver, ws=False):
    return ("path+file:///w/%s#%s" % (name, ver)) if ws else ("%s#%s@%s" % (REG, name, ver))


def make_meta(root):
    """A 7-package workspace: app -> core -> {libmit, copyleft-dep}; core build-dep {buildtool}; app dev-dep {devtool};
    libmit -> winonly (cfg(windows)); 'nolicense' has no licence at all."""
    def pkg(name, ver, license, ws=False, kind=("lib",), directory=None):
        d = directory or os.path.join(root, "crates", name)
        return {"name": name, "version": ver, "id": pid(name, ver, ws), "license": license, "license_file": None, "description": "d " + name,
                "source": None if ws else REG, "dependencies": [], "targets": [{"kind": list(kind), "name": name}], "features": {},
                "manifest_path": os.path.join(d, "Cargo.toml"), "repository": "https://example.invalid/" + name, "homepage": None}
    pkgs = [pkg("synofurb", "1.2.3", "MIT", True, ("bin",)), pkg("synofurb-core", "1.2.3", "MIT", True),
            pkg("libmit", "0.1.0", "MIT/Apache-2.0"), pkg("copyleft-dep", "2.0.0", "MPL-2.0"), pkg("buildtool", "3.0.0", "GPL-3.0-only"),
            pkg("devtool", "4.0.0", "Apache-2.0 OR GPL-2.0-only"), pkg("winonly", "0.9.0", "MIT"), pkg("nolicense", "0.0.1", None),
            pkg("weird", "1.0.0", "Foo-1.0 OR MIT")]

    def node(name, ver, ws, deps):
        return {"id": pid(name, ver, ws), "dependencies": [], "features": [],
                "deps": [{"name": d[0], "pkg": pid(d[0], d[1]), "dep_kinds": [{"kind": d[2], "target": d[3] if len(d) > 3 else None}]} for d in deps]}
    nodes = [node("synofurb", "1.2.3", True, [("synofurb-core", "1.2.3", None)]), node("synofurb-core", "1.2.3", True, [("libmit", "0.1.0", None), ("copyleft-dep", "2.0.0", None), ("buildtool", "3.0.0", "build"), ("nolicense", "0.0.1", None), ("weird", "1.0.0", None)]),
             node("libmit", "0.1.0", False, [("winonly", "0.9.0", None, "cfg(windows)")]), node("copyleft-dep", "2.0.0", False, []), node("buildtool", "3.0.0", False, []),
             node("devtool", "4.0.0", False, []), node("winonly", "0.9.0", False, []), node("nolicense", "0.0.1", False, []), node("weird", "1.0.0", False, [])]
    nodes[0]["deps"].append({"name": "devtool", "pkg": pid("devtool", "4.0.0"), "dep_kinds": [{"kind": "dev", "target": None}]})
    # the workspace member ids in cargo metadata have no registry source; fix the dep pkg ids that point at workspace crates
    nodes[0]["deps"][0]["pkg"] = pid("synofurb-core", "1.2.3", True)
    return {"packages": pkgs, "workspace_members": [pid("synofurb", "1.2.3", True), pid("synofurb-core", "1.2.3", True)],
            "resolve": {"root": None, "nodes": nodes}}


