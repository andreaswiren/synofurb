//! Builds `payload.tar.gz`: the configuration bundle the installer unpacks into the new system.
//!
//! Contents (relative to `/opt/synofurb-install` in the target):
//! `env.sh` (generated, no secrets except the password *hash*), `authorized_keys`,
//! `chroot-setup.sh`, `files/` (static config), `mgmt/` (management plane),
//! `plan.json` and `dsm-inspect.txt` (what the NAS looked like before the install).

use crate::config::{InstallConfig, sh_quote};
use crate::model::*;
use crate::plan::Plan;
use anyhow::Result;
use flate2::{Compression, write::GzEncoder};
use sha2::{Digest, Sha256};

macro_rules! asset {
    ($p:literal) => {
        ($p, include_str!(concat!(env!("CARGO_MANIFEST_DIR"), "/../../payload/", $p)))
    };
}

/// The management plane is its own project in the monorepo (`apps/mgmt-plane`); it is bundled under `mgmt/`.
macro_rules! mgmt_asset {
    ($bundle:literal, $file:literal) => {
        ($bundle, include_str!(concat!(env!("CARGO_MANIFEST_DIR"), "/../../apps/mgmt-plane/", $file)))
    };
}

/// Boot tooling lives in `boot/` (its own tested project); it is bundled into the payload.
macro_rules! boot_asset {
    ($bundle:literal, $file:literal) => {
        ($bundle, include_str!(concat!(env!("CARGO_MANIFEST_DIR"), "/../../boot/", $file)))
    };
}

/// The DOM boot-menu manager script (also placed into the installer initrd and uploaded to DSM).
pub const DOM_SCRIPT: &str = include_str!(concat!(env!("CARGO_MANIFEST_DIR"), "/../../boot/dom/synofurb-dom"));

/// (path inside the bundle, content, mode)
const STATIC_FILES: &[(&str, &str)] = &[
    asset!("chroot-setup.sh"),
    asset!("files/etc/ssh/sshd_config.d/10-synofurb.conf"),
    asset!("files/etc/udev/rules.d/90-synofurb-usb-serial.rules"),
    asset!("files/etc/systemd/network/10-synofurb-dhcp.network"),
    asset!("files/etc/avahi/services/synofurb.service"),
    asset!("files/etc/issue.d/10-synofurb.issue"),
    asset!("files/etc/apt/apt.conf.d/52synofurb-unattended"),
    asset!("files/etc/sysctl.d/90-synofurb.conf"),
    asset!("files/etc/systemd/system/synofurb-firstboot.service"),
    asset!("files/usr/local/sbin/synofurb-firstboot"),
    asset!("files/usr/local/sbin/synofurb-uboot-update"),
    asset!("files/usr/local/sbin/synofurb-dom-update"),
    boot_asset!("files/usr/local/sbin/synofurb-dom", "dom/synofurb-dom"),
    mgmt_asset!("mgmt/synofurb_mgmt.py", "synofurb_mgmt.py"),
    mgmt_asset!("mgmt/synofurb-mgmt.service", "synofurb-mgmt.service"),
    mgmt_asset!("mgmt/README.md", "README.md"),
    // `VERSION` is what `synofurb_mgmt.py health --json` and `manage health` report; the single source is apps/mgmt-plane/VERSION
    // (the same file `manage::MgmtBundle::embedded()` and `bundle create` ship).
    mgmt_asset!("mgmt/VERSION", "VERSION"),
];

pub struct Payload {
    pub bytes: Vec<u8>,
    pub sha256: String,
}

/// Offline mode: what `chroot-setup.sh` needs to know about the bundle's mirror.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct OfflineEnv {
    /// Suites present in the bundle (`trixie`, `trixie-backports`). Only these get an apt source during the install.
    pub suites: Vec<String>,
}

/// Render `env.sh`. All values are validated by [`InstallConfig::validate`] and single-quoted.
pub fn render_env(cfg: &InstallConfig, plan: &Plan, facts: &DeviceFacts) -> String {
    render_env_with(cfg, plan, facts, None)
}

/// [`render_env`] plus the offline variables (`OFFLINE=1`, `OFFLINE_SUITES`) when `offline` is given. The online
/// output is byte-identical to what it was before offline mode existed.
pub fn render_env_with(cfg: &InstallConfig, plan: &Plan, facts: &DeviceFacts, offline: Option<&OfflineEnv>) -> String {
    let mut e = String::from("# generated by synofurb\n");
    let mut kv = |k: &str, v: &str| {
        e.push_str(&format!("{k}={}\n", sh_quote(v)));
    };
    kv("NAS_HOSTNAME", &cfg.hostname);
    kv("USERNAME", &cfg.username);
    kv("PASSWORD_HASH", &cfg.password_hash);
    kv("TIMEZONE", &cfg.timezone);
    kv("LOCALE", &cfg.locale);
    kv("KEYMAP", &cfg.keymap);
    kv("MIRROR_HOST", &cfg.mirror_host);
    kv("MIRROR_DIR", &cfg.mirror_dir);
    kv("SUITE", &cfg.suite);
    kv("ARCH", plan.arch.debian());
    kv(
        "FIRMWARE",
        match plan.firmware {
            Firmware::Bios => "Bios",
            Firmware::Uefi => "Uefi",
            Firmware::UBoot => "UBoot",
            Firmware::Dom => "Dom",
        },
    );
    kv("GRUB_EFI_TARGET", plan.arch.grub_efi_target());
    kv("SERIAL_TTY", &cfg.serial.tty);
    kv("SERIAL_ARG", &cfg.serial.kernel_arg());
    kv("KERNEL_CHANNEL", if cfg.kernel == crate::config::KernelChannel::Newest { "newest" } else { "stable" });
    kv("CPU_VENDOR", facts.cpu_vendor.label());
    kv("MICROCODE_PKG", facts.cpu_vendor.microcode_package().unwrap_or(""));
    kv("DOM_BOOT", if plan.dom_boot { "1" } else { "0" });
    kv("SERIAL_SPEED", &cfg.serial.speed.to_string());
    kv("ENABLE_MGMT", if cfg.enable_mgmt { "1" } else { "0" });
    kv("EXTRA_PACKAGES", &cfg.extra_packages.join(" "));
    kv("DTB", cfg.dtb.as_deref().unwrap_or(""));
    kv("DSM_MODEL", &facts.model);
    if let Some(rb) = &plan.raw_boot {
        kv("KERNEL_MIB", &rb.kernel_mib.to_string());
        kv("INITRD_MIB", &rb.initrd_mib.to_string());
        kv("RESERVED_MIB", &rb.reserved_mib.to_string());
    }
    if let Some(o) = offline {
        kv("OFFLINE", "1");
        kv("OFFLINE_SUITES", &o.suites.join(" "));
    }
    e
}

pub fn build_payload(cfg: &InstallConfig, plan: &Plan, facts: &DeviceFacts, dsm_inspect_output: &str) -> Result<Payload> {
    build_payload_with(cfg, plan, facts, dsm_inspect_output, None)
}

/// Payload for an offline install: `env.sh` additionally carries `OFFLINE=1` and the bundle's suites.
pub fn build_payload_offline(
    cfg: &InstallConfig,
    plan: &Plan,
    facts: &DeviceFacts,
    dsm_inspect_output: &str,
    offline: &OfflineEnv,
) -> Result<Payload> {
    build_payload_with(cfg, plan, facts, dsm_inspect_output, Some(offline))
}

fn build_payload_with(
    cfg: &InstallConfig,
    plan: &Plan,
    facts: &DeviceFacts,
    dsm_inspect_output: &str,
    offline: Option<&OfflineEnv>,
) -> Result<Payload> {
    cfg.validate()?;
    if let Some(o) = offline {
        // the suite names end up in a shell word list: only lowercase letters and '-' are accepted
        if o.suites.is_empty() || o.suites.iter().any(|s| s.is_empty() || !s.chars().all(|c| c.is_ascii_lowercase() || c == '-')) {
            anyhow::bail!("invalid offline suite list");
        }
    }
    let gz = GzEncoder::new(Vec::new(), Compression::new(6));
    let mut tar = tar::Builder::new(gz);
    let mut add = |path: &str, data: &[u8], mode: u32| -> Result<()> {
        let mut h = tar::Header::new_gnu();
        h.set_size(data.len() as u64);
        h.set_mode(mode);
        h.set_mtime(0);
        h.set_uid(0);
        h.set_gid(0);
        tar.append_data(&mut h, path, data)?;
        Ok(())
    };
    for (path, content) in STATIC_FILES {
        let mode = if path.ends_with(".sh") || path.contains("usr/local/sbin/") { 0o755 } else { 0o644 };
        add(path, content.as_bytes(), mode)?;
    }
    add("env.sh", render_env_with(cfg, plan, facts, offline).as_bytes(), 0o600)?;
    add(
        "authorized_keys",
        (cfg.ssh_authorized_keys.join("\n") + if cfg.ssh_authorized_keys.is_empty() { "" } else { "\n" }).as_bytes(),
        0o600,
    )?;
    add("plan.json", serde_json::to_string_pretty(plan)?.as_bytes(), 0o644)?;
    add("dsm-inspect.txt", dsm_inspect_output.as_bytes(), 0o644)?;
    let bytes = tar.into_inner()?.finish()?;
    let sha256 = hex::encode(Sha256::digest(&bytes));
    Ok(Payload { bytes, sha256 })
}

