#!/usr/bin/env python3
"""Regenerates src/ui/tokens.rs from design/v2/tokens-v2.json (the UI designer's source of truth) and refreshes the
bundled copy of the GPUI theme set.  Run from the repo root:  python3 crates/synofurb/assets/theme/gen_tokens.py"""
import json, pathlib, shutil, sys
root = pathlib.Path(__file__).resolve().parents[4]
t = json.loads((root / "design/v2/tokens-v2.json").read_text())
shutil.copy(root / "design/v2/synofurb-theme.json", pathlib.Path(__file__).parent / "synofurb-theme.json")
names = [k[len("color.light."):] for k in t if k.startswith("color.light.")]
assert names == [k[len("color.dark."):] for k in t if k.startswith("color.dark.")], "light/dark token sets differ"
def table(mode):
    rows = []
    for n in names:
        v = t[f"color.{mode}.{n}"].lstrip("#").upper()
        assert len(v) == 6, (n, v)
        rows.append(f"    {n}: 0x{v},")
    return "\n".join(rows)
def consts(mode, ident):
    rows = [f"    {n}: 0x{t['color.'+mode+'.'+n].lstrip('#').upper()}," for n in names]
    return [f"pub const {ident}: Hexes = Hexes {{", *rows, "};", ""]
out = ["// @generated by crates/synofurb/assets/theme/gen_tokens.py from design/v2/tokens-v2.json. Do not edit by hand.",
       "use gpui_kit::{Hsla, rgb};", "",
       "/// Opaque sRGB hex values, one per colour token (names match tokens-v2.json without the theme prefix).",
       "#[derive(Clone, Copy, Debug, PartialEq, Eq)]", "pub struct Hexes {", *[f"    pub {n}: u32," for n in names], "}", "",
       "impl Hexes {", "    /// `(token name, value)` pairs, used by tests and tooling.", "    pub fn fields(&self) -> Vec<(&'static str, u32)> {",
       "        vec![" + ", ".join(f'("{n}", self.{n})' for n in names) + "]", "    }", "}", "",
       "/// The tokens converted to GPUI colours.", "#[derive(Clone, Copy, Debug)]", "pub struct Palette {", *[f"    pub {n}: Hsla," for n in names], "    pub dark: bool,", "}", "",
       "impl Palette {", "    pub fn from_hex(h: &Hexes, dark: bool) -> Palette {", "        Palette {", *[f"            {n}: rgb(h.{n}).into()," for n in names], "            dark,", "        }", "    }", "}", "",
       *consts("light","LIGHT"), *consts("dark","DARK")]
(root / "crates/synofurb/src/ui/tokens.rs").write_text("\n".join(out))
print("wrote", len(names), "tokens")
